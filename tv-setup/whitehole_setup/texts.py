HELP_TEXT = """\
Программе нужен доступ к телевизору по сети — это называется «отладка по сети» (ADB). \
Включается один раз. Телевизор и компьютер должны быть подключены к одному роутеру.

Android TV / Google TV (Sony, Philips, TCL, Haier, Hisense и др.)
1. Настройки → Об устройстве (или «Система → О системе»).
2. 7 раз подряд нажми на пункт «Сборка» — появится надпись «Вы стали разработчиком».
3. Назад → появится раздел «Для разработчиков».
4. Включи «Отладка по USB» и, если есть, «Отладка по сети» / «ADB по сети».
5. IP-адрес телевизора: Настройки → Сеть → твоя сеть (пригодится для ручного ввода).
На Android 11+ бывает «Беспроводная отладка» с кодом сопряжения — эта программа её не \
поддерживает, нужна обычная «Отладка по сети» (порт 5555).

Xiaomi Mi TV / Mi Box / TV Stick
Настройки → Настройки устройства → Об устройстве → 7 раз нажать «Сборка». \
Потом: Настройки устройства → Для разработчиков → «Отладка по USB» (и «Отладка по сети», \
если пункт есть). Названия пунктов на разных моделях могут немного отличаться.

Sber / Salute TV
Обычно так же, как на Android TV: «Об устройстве» → несколько раз нажать на версию \
сборки → «Для разработчиков» → отладка. На разных моделях пункты называются по-разному; \
если не находится — спроси поддержку производителя.

Яндекс ТВ (Tuvio, Hi, Leff, Яндекс ТВ Станция и др.)
На Яндекс ТВ отладка спрятана — в обычных настройках её нет. На многих телевизорах \
на платформе CVTE (Tuvio, Hi и др.) она включается в сервисном (заводском) меню: \
Factory Menu → DEBUG → ADB Enable. Как открыть это меню — зависит от модели \
(обычно специальная комбинация кнопок пульта). Точную комбинацию для своей модели \
лучше узнать в поддержке — напиши нам, подскажем. В сервисном меню больше ничего \
не меняй.

Какие телевизоры не подходят
Samsung (Tizen), LG (webOS), Hisense / Toshiba на VIDAA, Apple TV и другие телевизоры не на Android — \
не поддерживаются: на них нельзя поставить Android-приложения. Что можно сделать:
• купить недорогую Android TV-приставку (Xiaomi Mi Box / TV Stick, Яндекс Модуль и т. п.) и \
подключить её к HDMI — с ней всё работает;
• или включить WhiteHole на роутере — тогда VPN работает для всех устройств дома, включая такой \
телевизор (напиши в поддержку, подскажем).

Когда отладка включена
Нажми «Найти телевизор». На экране ТВ появится окно «Разрешить отладку?» — \
отметь «Всегда разрешать с этого компьютера» и нажми ОК.
"""

